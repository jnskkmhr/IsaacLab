"""Write the OSMO workflow that collects the dataset: one task per terrain and task group.

Submit the result with ``learning/osmo/run_collection.sh --workflow <yaml> OUTPUT_URI --pool POOL``. Every task writes
into the same dataset root (``<root>/<split>/<terrain>/<category>/NNNN.hdf5``), so the tasks can run independently.
"""

import argparse
from pathlib import Path

HEADER = """# Generated by dataset/osmo/make_workflow.py; do not edit by hand.
workflow:
  name: "{{ workflow_name }}"
  resources:
    default:
      gpu: __GPUS__
      cpu: __CPU__
      memory: __MEMORY__Gi
      storage: __STORAGE__Gi
      platform: "{{ platform }}"
  tasks:
"""

TASK = """  - name: __NAME__
    image: "{{ image }}"
    command: [bash, /tmp/run___NAME__.sh]
    environment:
      HEADLESS: "1"
      PYTHONUNBUFFERED: "1"
      NVIDIA_DRIVER_CAPABILITIES: compute,utility
      OMP_NUM_THREADS: "4"
      MKL_NUM_THREADS: "4"
      OPENBLAS_NUM_THREADS: "4"
      UV_PYTHON: "3.12"
      UV_PYTHON_PREFERENCE: only-managed
      UV_PROJECT_ENVIRONMENT: /tmp/isaaclab-venv
      UV_INSTALL_DIR: /tmp/uv
      UV_NO_MODIFY_PATH: "1"
      UV_VERSION: "{{ uv_version }}"
    files:
    - path: /tmp/run___NAME__.sh
      contents: |
        set -euo pipefail
        mkdir -p '{{output}}/logs'
        exec > >(tee -a "{{output}}/logs/__NAME__.stdout.log") 2>&1
        printf '%s  %s\\n' '{{ source_sha256 }}' '{{input:0}}/source.tar.gz' | sha256sum --check --strict
        mkdir -p /tmp/isaaclab
        tar -xzf '{{input:0}}/source.tar.gz' -C /tmp/isaaclab
        unset PYTHONPATH VIRTUAL_ENV DISPLAY
        export PATH="/tmp/uv:$PATH"
        if ! command -v uv >/dev/null; then
          curl --fail --location --retry 3 "https://astral.sh/uv/{{ uv_version }}/install.sh" | sh
        fi
        cd /tmp/isaaclab
        uv sync --locked --no-dev
        cp bundle_manifest.json '{{output}}/logs/bundle_manifest___NAME__.json' || true
        export PYTHONPATH=/tmp/isaaclab/examples
        uv run --no-sync python -m particle_nerd_benchmark.dataset.run_jobs \\
          --terrain __TERRAIN__ --select __SELECT__ --gpus __GPUS__ --per-motion {{ per_motion }} \\
          --g1-checkpoint '{{input:1}}/model_19999.pt' --output '{{output}}'
    inputs:
    - url: "{{ source_url }}"
    - url: "{{ ckpt_url }}"
    outputs:
    - url: "{{ output_url }}"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--terrains", nargs="+", default=["flat", "slope", "wave"])
    parser.add_argument("--select", nargs="+", default=["lateral", "vertical_impact", "rest_sand", "robots"])
    parser.add_argument("--per-motion", type=int, default=29, help="Episodes per motion (test run: 1)")
    parser.add_argument(
        "--ckpt-url", required=True, help="swift:// folder with the G1 model_19999.pt and training_config.json"
    )
    parser.add_argument("--gpus", type=int, default=2)
    parser.add_argument("--storage", type=int, default=260, help="Disk per task [Gi]; some pools cap it per GPU")
    parser.add_argument("--platform", default="ovx-l40s")
    parser.add_argument("--combine", action="store_true", help="One task per terrain running every selected group")
    parser.add_argument("--name", default="particle-nerd-dataset")
    args = parser.parse_args()

    text = (
        HEADER.replace("__GPUS__", str(args.gpus))
        .replace("__CPU__", str(14 * args.gpus))
        .replace("__MEMORY__", str(64 * args.gpus))
        .replace("__STORAGE__", str(args.storage))
    )
    for terrain in args.terrains:
        for group in [" ".join(args.select)] if args.combine else args.select:
            name = (f"{terrain}-all" if args.combine else f"{terrain}-{group}").replace("_", "-")
            text += (
                TASK.replace("__NAME__", name)
                .replace("__TERRAIN__", terrain)
                .replace("__SELECT__", group)
                .replace("__GPUS__", str(args.gpus))
            )
    text += f"""
default-values:
  workflow_name: {args.name}
  image: nvcr.io/nvidia/isaac-lab:3.0.0-rc1
  platform: {args.platform}
  uv_version: 0.12.12
  per_motion: {args.per_motion}
  ckpt_url: "{args.ckpt_url}"
  output_url: ""
  source_url: ""
  source_sha256: ""
"""
    args.out.write_text(text)
    print(f"wrote {args.out} with {len(args.terrains) * len(args.select)} tasks")


if __name__ == "__main__":
    main()
